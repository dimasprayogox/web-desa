// Helper function untuk filter UMKM
export const filterUmkm = (umkmArray, { searchQuery = "", kategoriId = "", page = 1, perPage = 9 }) => {
  let filtered = [...umkmArray];

  // Filter by search query
  if (searchQuery) {
    const query = searchQuery.toLowerCase();
    filtered = filtered.filter(
      (item) =>
        item.nama.toLowerCase().includes(query) ||
        item.deskripsi.toLowerCase().includes(query) ||
        item.pemilik.toLowerCase().includes(query)
    );
  }

  // Filter by kategori
  if (kategoriId) {
    filtered = filtered.filter((item) => item.kategori_id === parseInt(kategoriId));
  }

  // Pagination
  const total = filtered.length;
  const lastPage = Math.ceil(total / perPage);
  const startIndex = (page - 1) * perPage;
  const endIndex = startIndex + perPage;
  const paginatedData = filtered.slice(startIndex, endIndex);

  return {
    data: paginatedData,
    pagination: {
      current_page: page,
      last_page: lastPage,
      per_page: perPage,
      total: total,
    },
  };
};